import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { describe, expect, it } from "vitest";
import { repoRoot } from "./support";

const lib = (await import(pathToFileURL(join(repoRoot, "tools/lib/pr-body.mjs")).href)) as {
  FOOTER: string;
  validateBody(text: unknown): string[];
  validateTitle(text: unknown): string[];
  countWords(text: string): number;
};

const FOOTER = "🤖 Generated with [Claude Code](https://claude.com/claude-code)";
const good = `> [!NOTE]\n> Adds the release script.\n\nThe script reads the config file. Tests use a fake registry.\n\n${FOOTER}\n`;

describe("validateBody", () => {
  it("accepts a good body with one trailing newline, and one without", () => {
    expect(lib.validateBody(good)).toEqual([]);
    expect(lib.validateBody(good.slice(0, -1))).toEqual([]);
    expect(lib.FOOTER).toBe(FOOTER);
  });

  it("accepts every alert type", () => {
    for (const type of ["NOTE", "TIP", "IMPORTANT", "CAUTION", "WARNING"]) {
      expect(lib.validateBody(good.replace("NOTE", type)), type).toEqual([]);
    }
  });

  it("refuses a body that is not text or is empty", () => {
    expect(lib.validateBody(undefined)).not.toEqual([]);
    expect(lib.validateBody(42)).not.toEqual([]);
    expect(lib.validateBody("")).not.toEqual([]);
  });

  it("refuses a first line that is not an alert", () => {
    expect(lib.validateBody(good.replace("> [!NOTE]", "Summary")).join()).toMatch(/first line/);
    expect(lib.validateBody(good.replace("[!NOTE]", "[!INFO]")).join()).toMatch(/first line/);
    expect(lib.validateBody(good.replace("> [!NOTE]", "[!NOTE]")).join()).toMatch(/first line/);
    expect(lib.validateBody(`\n${good}`).join()).toMatch(/first line/);
    expect(lib.validateBody(good.replace("> [!NOTE]", "> [!NOTE] extra")).join()).toMatch(/first line/);
  });

  it("allows exactly 300 words and refuses 301", () => {
    const filler = (count: number) => Array.from({ length: count }, () => "word").join(" ");
    const base = (count: number) => `> [!NOTE]\n> ${filler(count)}\n\n${FOOTER}\n`;
    const fixed = lib.countWords(base(0));
    expect(lib.validateBody(base(300 - fixed))).toEqual([]);
    expect(lib.validateBody(base(301 - fixed)).join()).toMatch(/301 words/);
  });

  it("counts words without a quadratic cost on a long body of spaces", () => {
    const text = `> [!NOTE]\n${" ".repeat(200000)}x\n${FOOTER}\n`;
    const start = Date.now();
    lib.validateBody(text);
    expect(Date.now() - start).toBeLessThan(500);
  });

  it("refuses a straight-apostrophe contraction", () => {
    for (const word of ["don't", "it's", "we're", "we've", "they'll", "I'd", "I'm"]) {
      expect(lib.validateBody(good.replace("reads", `${word} reads`)).join(), word).toMatch(/contraction/);
    }
  });

  it("refuses curly-apostrophe contractions", () => {
    expect(lib.validateBody(good.replace("reads", "doesn\u2019t read")).join()).toMatch(/contraction/);
    expect(lib.validateBody(good.replace("reads", "doesn\u02bct read")).join()).toMatch(/contraction/);
  });

  it("does not flag quotes that are not contractions", () => {
    expect(lib.validateBody(good.replace("reads", "reads the 'config' and")).join()).not.toMatch(/contraction/);
  });

  it("refuses a body that does not end with the footer line", () => {
    expect(lib.validateBody(good.replace(FOOTER, "Generated by hand")).join()).toMatch(/end/);
    expect(lib.validateBody(good.replace(FOOTER, FOOTER.replace("claude-code", "other"))).join()).toMatch(/end/);
  });

  it("refuses text after the footer, a footer that is not on its own line, and a footer with trailing spaces", () => {
    expect(lib.validateBody(`${good}More text\n`).join()).toMatch(/end/);
    expect(lib.validateBody(`> [!NOTE]\n> Hi.\n\nText ${FOOTER}\n`).join()).toMatch(/end/);
    expect(lib.validateBody(good.replace(`${FOOTER}\n`, `${FOOTER} \n`)).join()).toMatch(/end/);
  });

  it("refuses the trailing-newline loophole: extra blank lines after the footer", () => {
    expect(lib.validateBody(`${good}\n`).join()).toMatch(/end/);
    expect(lib.validateBody(`${good}\n\n\n`).join()).toMatch(/end/);
    expect(lib.validateBody(`${good.slice(0, -1)}\n \n`).join()).toMatch(/end/);
  });

  it("refuses carriage returns", () => {
    expect(lib.validateBody(good.replaceAll("\n", "\r\n")).join()).toMatch(/carriage return|CRLF/i);
  });

  it("refuses a home path", () => {
    expect(lib.validateBody(good.replace("config file", "file at /Users/someone/project")).join()).toMatch(/home path/);
    expect(lib.validateBody(good.replace("config file", "file at /home/someone/x")).join()).toMatch(/home path/);
    expect(lib.validateBody(good.replace("config file", "file at C:\\Users\\someone\\x")).join()).toMatch(/home path/);
  });

  it("refuses a session link", () => {
    expect(lib.validateBody(good.replace("config file", "link https://claude.ai/code/session_0123456789abcdef")).join()).toMatch(/session link/);
    expect(lib.validateBody(good.replace("config file", "id session_0123456789abcdef")).join()).toMatch(/session link/);
  });

  it("does not take the footer link for a session link", () => {
    expect(lib.validateBody(good).join()).not.toMatch(/session link/);
  });

  it("reports every problem it finds", () => {
    const problems = lib.validateBody("Not an alert, it's long\n");
    expect(problems.length).toBeGreaterThanOrEqual(3);
  });

  it("counts words that are separated only by zero-width characters", () => {
    for (const mark of ["\u200b", "\u200c", "\u200d", "\u2060", "\ufeff"]) {
      const text = `> [!NOTE]\n> ${Array.from({ length: 500 }, () => "word").join(mark)}\n\n${FOOTER}\n`;
      expect(lib.validateBody(text).join(), JSON.stringify(mark)).toMatch(/words/);
    }
  });

  it("counts words that are separated by other Unicode spaces", () => {
    const text = `> [!NOTE]\n> ${Array.from({ length: 500 }, () => "word").join("\u00a0")}\n\n${FOOTER}\n`;
    expect(lib.validateBody(text).join()).toMatch(/words/);
  });

  it("refuses contractions written with other apostrophes, with capitals, or with wide characters", () => {
    for (const word of ["DON\u2019T", "isn\u2018t", "we\u2019re", "they\uff07ll", "it\u2032s", "Y\u02b9all\u02b9d"]) {
      expect(lib.validateBody(good.replace("reads", `${word} reads`)).join(), word).toMatch(/contraction/);
    }
  });

  it("refuses contractions after non-English letters", () => {
    expect(lib.validateBody(good.replace("reads", "caf\u00e9\u2019s reads")).join()).toMatch(/contraction/);
  });

  it("finds a home path or a session link hidden with invisible characters", () => {
    const hidden = [
      "file at /Us\u200bers/someone/x",
      "file at /Us\u00aders/someone/x",
      "file at /ho\u2060me/someone/x",
      "link https://claude.ai/c\u200bode/session_0123456789abcdef",
      "link https://claude.a\u00ad\u200di/chat/x",
      "file at \uff0fUsers\uff0fsomeone",
    ];
    for (const text of hidden) {
      const problems = lib.validateBody(good.replace("config file", text)).join();
      expect(problems, JSON.stringify(text)).toMatch(/home path|session link/);
    }
  });

  it("finds a home path or a session link hidden behind format, selector, tag, or filler characters", () => {
    const hidden = [0xFE0F, 0x180B, 0xE0041, 0x115F, 0x1160, 0x3164, 0xFFA0, 0x200B, 0x00AD, 0x2062];
    for (const code of hidden) {
      const mark = String.fromCodePoint(code);
      const path = lib.validateBody(good.replace("config file", `file at /Us${mark}ers/someone/x`)).join();
      expect(path, code.toString(16)).toMatch(/home path/);
      const link = lib.validateBody(good.replace("config file", `link https://claude${mark}.ai/code/x`)).join();
      expect(link, code.toString(16)).toMatch(/session link/);
    }
  });

  it("finds paths and links written in other forms", () => {
    const forms = [
      "file at C:\\Users\\someone\\x",
      "file at \\Users\\someone\\x",
      "file at %2FUsers%2Fsomeone%2Fx",
      "file at &#47;Users&#47;someone",
      "file at &#x2F;Users&#x2F;someone",
      "file at &sol;home&sol;someone",
      "link https://claude.ai/artifact/abc",
      "link https://claude.ai/local_sessions/abc",
    ];
    for (const text of forms) {
      const problems = lib.validateBody(good.replace("config file", text)).join();
      expect(problems, text).toMatch(/home path|session link/);
    }
  });

  it("removes default-ignorable characters and control characters before every check", () => {
    for (const code of [0x17b4, 0x17b5, 0x2800, 0x0007, 0x034f, 0x00a0 + 0x0000]) {
      const mark = String.fromCodePoint(code);
      if (code !== 0x00a0) {
        expect(lib.validateBody(good.replace("config file", `file at /Us${mark}ers/x`)).join(), code.toString(16)).toMatch(/home path/);
        expect(lib.validateBody(good.replace("reads", `don${mark}\u2019t reads`)).join(), code.toString(16)).toMatch(/contraction/);
      }
      const words = `> [!NOTE]\n> ${Array.from({ length: 500 }, () => "word").join(mark)}\n\n${FOOTER}\n`;
      expect(lib.validateBody(words).join(), code.toString(16)).toMatch(/words/);
    }
  });
});

describe("validateTitle", () => {
  it("accepts a plain title", () => {
    expect(lib.validateTitle("Add the release script")).toEqual([]);
  });

  it("refuses a title with a contraction, a home path, or a session link, also when it is hidden", () => {
    for (const title of ["it's done", "fix /Users/someone/x", "see claude.ai/code/x", "fix /Us\u200bers/x", "fix %2FUsers%2Fx", "see claude\ufe0f.ai/code/x"]) {
      expect(lib.validateTitle(title).length, title).toBeGreaterThan(0);
    }
  });
});
